function fenced(help: string): string {
  // Strip exactly one trailing newline, matching helpText() in src/cli.ts, so
  // the skill renders a help string the same way the CLI prints it.
  return `\`\`\`text\n${help.replace(/\n$/, '')}\n\`\`\``;
}

function catalog(): string[] {
  const families = Object.keys(FAMILY_HELP);
  const sections: string[] = [];
  for (const [command, help] of Object.entries(HELP)) {
    if (!families.some((family) => command.startsWith(`${family} `))) {
      sections.push(`### ${command}`, fenced(help));
    }
  }
  for (const [family, familyHelp] of Object.entries(FAMILY_HELP)) {
    sections.push(`### ${family}`, fenced(familyHelp));
    for (const [command, help] of Object.entries(HELP)) {
      if (command.startsWith(`${family} `)) {
        sections.push(`#### ${command}`, fenced(help));
      }
    }
  }
  return sections;
}

export function renderSkill(): string {
  const sections = [
    `---\nname: ${SKILL_NAME}\ndescription: "${SKILL_DESCRIPTION.replace(/["\\]/g, '\\$&')}"\n---`,
    GENERATED_NOTE,
    `# ${SKILL_NAME}`,
    `${DESCRIPTION}.`,
    GUIDANCE,
    fenced(TOP_HELP),
    ...catalog(),
  ];
  return `${sections.join('\n\n')}\n`;
}
